import { render, screen, within, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { expect, it, vi } from 'vitest';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { SortableRow } from './SortableRow';
import { TooltipProvider } from '../ui/tooltip';
import type { QueueItem } from './types';
vi.mock('@/components/ui/toast-context', () => ({ useToast: () => ({ toast: vi.fn() }) }));
vi.mock('@dnd-kit/sortable', () => ({ useSortable: () => ({ attributes: {}, listeners: {}, setNodeRef: vi.fn() }) }));
it('mostra badges e tooltip de tags, preserva prioridade e rascunho de descrição no erro', async () => {
  const save = vi.fn().mockRejectedValueOnce(new Error('500')).mockResolvedValueOnce(undefined);
  const item = { id: 1, title: 'Título longo da questão', item_type: 'PROBLEM', source_platform: 'CF_OFFICIAL', tags: ['math', 'dp', 'graphs'], priority: 'P1', description: 'anterior', contest_name: 'Treino' } as QueueItem;
  render(<QueryClientProvider client={new QueryClient()}><TooltipProvider><table><tbody><SortableRow item={item} onToggle={vi.fn()} onPatchPriority={vi.fn()} onPatchDescription={save} /></tbody></table></TooltipProvider></QueryClientProvider>);
  const user = userEvent.setup();
  expect(screen.queryByText(/Ver.*tags/)).toBeNull();
  const tags = screen.getByRole('button', { name: 'Todas as tags' });
  for (let i = 0; i < 6 && document.activeElement !== tags; i++) await user.tab();
  expect(tags).toHaveFocus();
  expect(await screen.findByRole('tooltip')).toHaveTextContent('graphs');
  const row = screen.getByRole('row');
  expect(within(row).getByRole('button', { name: /Prioridade/ })).toBeVisible();
  await user.click(screen.getByRole('button', { name: 'Editar descrição' }));
  const input = screen.getByRole('textbox', { name: 'Editar descrição' });
  await user.clear(input); await user.type(input, 'nova nota{Enter}');
  expect(await screen.findByRole('alert')).toHaveTextContent('Não foi salvo');
  expect(screen.getByDisplayValue('nova nota')).toBeVisible();
  await user.type(input, '{Enter}');
  await waitFor(() => expect(screen.queryByRole('textbox')).toBeNull());
  expect(save).toHaveBeenCalledTimes(2);
});
